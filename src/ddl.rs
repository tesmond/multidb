//! `CREATE TABLE` statements for the navigator's "SQL Template" menu, read
//! from the database itself so they match how the table was really created.
//! The table name is left unqualified: the query tab opens with the table's
//! schema as its default schema.

use crate::backup::{qualified_table_name, quote_identifier};
use anyhow::{anyhow, Result};
use sqlx::{MySqlPool, PgPool, Row, SqlitePool};

/// Columns, then table constraints, then the indexes no constraint owns.
pub async fn postgres_create_table(pool: &PgPool, schema: &str, table: &str) -> Result<String> {
    let rel = qualified_table_name("postgres", table, schema);
    let name: String = sqlx::query_scalar("SELECT quote_ident($1)").bind(table).fetch_one(pool).await?;
    let columns = sqlx::query(
        r#"
        SELECT quote_ident(a.attname)
               || ' ' || pg_catalog.format_type(a.atttypid, a.atttypmod)
               || CASE a.attidentity
                      WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                      WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                      ELSE ''
                  END
               || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
               || CASE WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END
        FROM pg_attribute a
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = $1::regclass
          AND a.attnum > 0
          AND NOT a.attisdropped
        ORDER BY a.attnum
        "#,
    )
    .bind(&rel)
    .fetch_all(pool)
    .await?;
    let constraints = sqlx::query(
        r#"
        SELECT 'CONSTRAINT ' || quote_ident(conname) || ' ' || pg_get_constraintdef(oid)
        FROM pg_constraint
        WHERE conrelid = $1::regclass
          AND contype IN ('p', 'u', 'c', 'f', 'x')
        ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'f' THEN 3 ELSE 4 END, conname
        "#,
    )
    .bind(&rel)
    .fetch_all(pool)
    .await?;
    let indexes = sqlx::query(
        r#"
        SELECT pg_get_indexdef(i.indexrelid)
        FROM pg_index i
        JOIN pg_class c ON c.oid = i.indexrelid
        WHERE i.indrelid = $1::regclass
          AND NOT EXISTS (
              SELECT 1 FROM pg_constraint k WHERE k.conrelid = i.indrelid AND k.conindid = i.indexrelid
          )
        ORDER BY c.relname
        "#,
    )
    .bind(&rel)
    .fetch_all(pool)
    .await?;
    if columns.is_empty() {
        return Err(anyhow!("table {rel} has no columns"));
    }
    let mut lines = Vec::new();
    for row in columns.iter().chain(constraints.iter()) {
        lines.push(row.try_get::<String, _>(0)?);
    }
    let mut indexes_sql = Vec::new();
    for row in &indexes {
        indexes_sql.push(row.try_get::<String, _>(0)?);
    }
    Ok(assemble(&name, &lines, &indexes_sql))
}

/// MySQL's own `SHOW CREATE TABLE`, which already carries the keys, indexes
/// and table options and names the table without its database.
pub async fn mysql_create_table(pool: &MySqlPool, schema: &str, table: &str) -> Result<String> {
    let rel = qualified_table_name("mysql", table, schema);
    let row = sqlx::query(&format!("SHOW CREATE TABLE {rel}")).fetch_one(pool).await?;
    let sql = match row.try_get::<String, _>(1) {
        Ok(sql) => sql,
        Err(_) => String::from_utf8_lossy(&row.try_get::<Vec<u8>, _>(1)?).into_owned(),
    };
    Ok(format!("{};\n", sql.trim().trim_end_matches(';')))
}

/// SQLite keeps the statements each table and index was created with.
pub async fn sqlite_create_table(pool: &SqlitePool, table: &str) -> Result<String> {
    let rows: Vec<(String, String)> = sqlx::query_as(
        r#"
        SELECT type, sql
        FROM sqlite_master
        WHERE tbl_name = ? AND type IN ('table', 'index') AND sql IS NOT NULL
        ORDER BY type = 'index', name
        "#,
    )
    .bind(table)
    .fetch_all(pool)
    .await?;
    if !rows.iter().any(|(kind, _)| kind == "table") {
        return Err(anyhow!("table {} not found", quote_identifier("sqlite", table)));
    }
    let statements: Vec<String> = rows
        .into_iter()
        .map(|(_, sql)| format!("{};", sql.trim().trim_end_matches(';')))
        .collect();
    Ok(statements.join("\n\n") + "\n")
}

fn assemble(name: &str, lines: &[String], indexes: &[String]) -> String {
    let mut out = format!("CREATE TABLE {name} (\n    {}\n);\n", lines.join(",\n    "));
    for index in indexes {
        out.push('\n');
        out.push_str(index);
        out.push_str(";\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::assemble;

    #[test]
    fn assembles_columns_constraints_and_indexes() {
        let sql = assemble(
            "users",
            &["id integer NOT NULL".into(), "email text".into(), "CONSTRAINT users_pkey PRIMARY KEY (id)".into()],
            &["CREATE INDEX users_email_idx ON public.users USING btree (email)".into()],
        );
        assert_eq!(
            sql,
            "CREATE TABLE users (\n    id integer NOT NULL,\n    email text,\n    CONSTRAINT users_pkey PRIMARY KEY (id)\n);\n\nCREATE INDEX users_email_idx ON public.users USING btree (email);\n"
        );
    }
}
